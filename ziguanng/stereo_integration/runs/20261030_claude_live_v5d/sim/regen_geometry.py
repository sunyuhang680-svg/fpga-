"""live_v5d: regenerate stereo triangulation and depth-ROI constants from jw's new 60fps
pairs (20261030_203705_878327). ki (renderer 640x720 domain) unchanged.
Checks first that the OLD R/T reproduces the files in the current build exactly."""
import json,re,numpy as np,hashlib
B='/mnt/project-files/testing60_diag/'
g=json.load(open(B+'merged_v1/device/calib/geometry_result.json'))
KiL=np.array(g['ki']['left'],float).reshape(3,3)/2**30;KiR=np.array(g['ki']['right'],float).reshape(3,3)/2**30
q30=lambda x:int(round(x*2**30))
def roi_coef(R,T,depths=(80.,500.)):
    KL=np.linalg.inv(KiL);KR=np.linalg.inv(KiR);n=np.array([0,0,1.]);res=[]
    for d in depths:
        H=KR@(R+np.outer(T,n)/d)@KiL;res.append(H/H[2,2])
    m=R@n
    for d in depths:
        dp=d+(R.T@T)@n;H=KL@R.T@(np.eye(3)-np.outer(T,m)/dp)@KiR;res.append(H/H[2,2])
    return [q30(x) for H in res for x in H.flatten()]
def tri_text(src,R,T):
    RT=R.T;Cr=-RT@T;vals=iter([q30(x) for x in RT.flatten()])
    t,n=re.subn(r"ma=(-?)32'sd(\d+);",lambda m:(lambda v:f"ma={'-' if v<0 else ''}32'sd{abs(v)};")(next(vals)),src);assert n==9
    for i,v in zip((6,7,8),[int(round(x*65536)) for x in Cr]):
        t,n=re.subn(r"r\[%d\] <= -?32'sd\d+;"%i,f"r[{i}] <= {'-' if v<0 else ''}32'sd{abs(v)};",t);assert n==1
    return t
def roi_text(src,coef):
    it=iter(coef)
    t,n=re.subn(r"(\d+): coefficient=(-?)40'sd(\d+);",lambda m:(lambda v:f"{m.group(1)}: coefficient={'-' if v<0 else ''}40'sd{abs(v)};")(next(it)),src);assert n==36
    return t
tri_src=open(B+'merged_v1/device/rtl/measurement_v1/stereo_triangulate_q24.sv',newline='').read()
roi_src=open(B+'live_v5b/rtl/measurement_v1/stereo_depth_roi.sv',newline='').read()
Ro=np.array(g['R']);To=np.array(g['T'])
assert tri_text(tri_src,Ro,To)==tri_src,'old R/T does not reproduce triangulate'
assert roi_text(roi_src,roi_coef(Ro,To))==roi_src,'old R/T does not reproduce roi'
print('old R/T reproduces both build files exactly')
c=json.load(open('/mnt/project-files/stereo_calib_v2/compare_rt.json'))
Rn=np.array(c['new_RT']['R']);Tn=np.array(c['new_RT']['T'])
tri_new=tri_text(tri_src,Rn,Tn).replace('// Regenerated by gen_geometry.py (claude merged_v1) from stereo_free_result.json R/T + active ki;',
  '// Regenerated by live_v5d regen_geometry.py from 60fps pairs 20261030_203705_878327 R/T + active ki;')
NEW_Z=(100.,500.)  # new R/T tilts epipolar lines; 80 mm overflows the 31-row window off-centre
roi_new=roi_text(roi_src,roi_coef(Rn,Tn,NEW_Z))
O='/mnt/project-files/testing60_diag/live_v5d/rtl/measurement_v1/'
open(O+'stereo_triangulate_q24.sv','w',newline='').write(tri_new)
open(O+'stereo_depth_roi.sv','w',newline='').write(roi_new)
json.dump(dict(R=Rn.tolist(),T=Tn.tolist(),roi_depths_mm=NEW_Z,roi_coef=roi_coef(Rn,Tn,NEW_Z),source='20261030_203705_878327'),open('geometry_v5d.json','w'),indent=1)
for f in ('stereo_triangulate_q24.sv','stereo_depth_roi.sv'):print(f,hashlib.sha256(open(O+f,'rb').read()).hexdigest())
